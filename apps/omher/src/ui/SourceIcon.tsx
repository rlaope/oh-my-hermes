/** The app mark for `source`, `size` px square. Decorative: the place name next to it carries the meaning. */
export function SourceIcon({ source, size = 12, style }: { source: string; size?: number; style?: CSSProperties }) {
  const common = {
    width: size,
    height: size,
    viewBox: "0 0 24 24",
    "aria-hidden": true as const,
    focusable: false as const,
    className: `src-ic src-ic-${source}`,
    "data-src": source,
    style,
  };
  switch (source) {
    case "slack":
      return (
        <svg {...common} viewBox="0 0 54 54">
          <SlackMark />
        </svg>
      );
    case "discord":
      return (
        <svg {...common}>
          <path d={DISCORD} fill="#5865F2" />
        </svg>
      );
    case "telegram":
      return (
        <svg {...common}>
          <path d={TELEGRAM} fill="#26A5E4" />
        </svg>
      );
    case "cron":
      return (
        <svg {...common} fill="none" stroke="currentColor" strokeWidth="2.2" strokeLinecap="round">
          <circle cx="12" cy="12" r="9" />
          <path d="M12 7v5l3 2" />
        </svg>
      );
    default:
      return (
        <svg {...common}>
          <circle cx="12" cy="12" r="5" fill="currentColor" />
        </svg>
      );
  }
}
