#!/usr/bin/env node
// Carries Orca's terminal palettes into omher: reads a clone of stablyai/orca and writes
// src/sessions/term/themes-orca.ts. Run from apps/omher:
//
//   node scripts/import-orca-themes.mjs <path to the orca clone>
//
// It reads the five theme files under src/shared/terminal-themes/ (in the order Orca's own catalog lists them)
// and the five GitHub palettes its bundled theme plugin names in orca-plugin.json. Every colour key Orca gives is
// kept as written; nothing is added. `kind` comes from the background's luminance (the rule Orca uses to tell a
// light terminal from a dark one). The palettes are data under the MIT licence: see THIRD_PARTY_NOTICES.md.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "src", "sessions", "term", "themes-orca.ts");
const THEME_DIR = "src/shared/terminal-themes";
// the order of Orca's THEME_CATEGORIES (defaults, popular dark, popular light, classic)
const FILES = ["defaults", "popular-dark-core", "popular-dark-extended", "popular-light", "classic"];
const PLUGIN = "resources/plugins/launch/stablyai.orca-github-vscode-theme";

const ANSI = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"];
const REQUIRED = ["background", "foreground", ...ANSI, ...ANSI.map((c) => `bright${c[0].toUpperCase()}${c.slice(1)}`)];
// xterm's ITheme keys, in the order the output writes them
const ORDER = [
  "background",
  "foreground",
  "cursor",
  "cursorAccent",
  "selectionBackground",
  "selectionForeground",
  "selectionInactiveBackground",
  ...REQUIRED.slice(2),
];
const HEX = /^#(?:[0-9a-f]{6}|[0-9a-f]{8})$/;

const clone = process.argv[2];
if (!clone) {
  console.error("usage: node scripts/import-orca-themes.mjs <path to the orca clone>");
  process.exit(2);
}

/** A TypeScript module's exports (the theme files hold only object literals and a type import). */
async function load(file) {
  const js = ts.transpileModule(readFileSync(file, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022, verbatimModuleSyntax: false },
  }).outputText;
  return import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
}

const linear = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  return 0.2126 * linear(r) + 0.7152 * linear(g) + 0.0722 * linear(b);
}
/** Light when black text contrasts with it at least as well as white text does. */
const kindOf = (background) => {
  const l = luminance(background);
  return (l + 0.05) / 0.05 >= 1.05 / (l + 0.05) ? "light" : "dark";
};

const slug = (name) =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const themes = [];
function add(name, palette, from, mode) {
  const theme = {};
  for (const [key, raw] of Object.entries(palette)) {
    if (!ORDER.includes(key)) throw new Error(`${from}: ${name} has a colour key this script does not know: ${key}`);
    const value = String(raw).toLowerCase();
    if (!HEX.test(value)) throw new Error(`${from}: ${name}.${key} is not a hex colour: ${raw}`);
    theme[key] = value;
  }
  for (const key of REQUIRED) if (!theme[key]) throw new Error(`${from}: ${name} has no ${key}`);
  const kind = kindOf(theme.background);
  if (mode && mode !== kind) throw new Error(`${from}: ${name} says ${mode} but its background is ${kind}`);
  const id = slug(name);
  if (themes.some((t) => t.id === id || t.name === name)) throw new Error(`${from}: ${name} is there twice`);
  themes.push({ id, name, kind, theme });
}

for (const f of FILES) {
  const from = `${THEME_DIR}/${f}.ts`;
  const maps = Object.values(await load(join(clone, from)));
  if (maps.length !== 1) throw new Error(`${from}: expected one exported theme map, found ${maps.length}`);
  for (const [name, palette] of Object.entries(maps[0])) add(name, palette, from);
}
const plugin = JSON.parse(readFileSync(join(clone, PLUGIN, "orca-plugin.json"), "utf8"));
for (const entry of plugin.contributes.terminalThemes) {
  const from = `${PLUGIN}/${entry.path}`;
  const doc = JSON.parse(readFileSync(join(clone, PLUGIN, entry.path), "utf8"));
  add(entry.title, doc.terminal, from, doc.mode);
}

let commit = "unknown";
try {
  commit = execFileSync("git", ["-C", clone, "rev-parse", "--short=8", "HEAD"], { encoding: "utf8" }).trim();
} catch {
  /* not a git checkout: the header says so */
}

const lines = [
  "// GENERATED by scripts/import-orca-themes.mjs: do not edit by hand, run the script again.",
  `// Source: stablyai/orca at ${commit}: ${FILES.map((f) => `${f}.ts`).join(", ")} under ${THEME_DIR}/,`,
  `// and the terminal palettes of ${PLUGIN.split("/").pop()}.`,
  "// The palettes are MIT-licensed data: Copyright (c) 2026 Lovecast Inc. (Orca) and Copyright (c) 2020 Primer",
  "// (the five GitHub palettes). Both notices are in apps/omher/THIRD_PARTY_NOTICES.md.",
  'import type { TermTheme } from "./themes";',
  "",
  `/** ${themes.length} themes, in Orca's own order: its catalog, then the GitHub palettes. */`,
  "export const ORCA_TERM_THEMES: readonly TermTheme[] = [",
];
for (const t of themes) {
  lines.push("  {", `    id: ${JSON.stringify(t.id)},`, `    name: ${JSON.stringify(t.name)},`, `    kind: ${JSON.stringify(t.kind)},`, "    theme: {");
  for (const key of ORDER) if (t.theme[key]) lines.push(`      ${key}: ${JSON.stringify(t.theme[key])},`);
  lines.push("    },", "  },");
}
lines.push("];", "");
writeFileSync(OUT, lines.join("\n"));
const dark = themes.filter((t) => t.kind === "dark").length;
console.log(`${themes.length} themes (${dark} dark, ${themes.length - dark} light) from orca ${commit} -> ${OUT}`);
