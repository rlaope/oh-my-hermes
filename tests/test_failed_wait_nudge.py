"""A turn a failed watcher opened, and that arms nothing, gets told so.

The second entrance to the stall `test_remote_wait_nudge.py` covers. The CI
check or merge watcher a session armed exits non-zero, the host's completion
notice opens a turn, the turn reports the failure, and it ends with nothing
armed: nothing will wake the session again, and the authorized fix, push,
re-watch and merge wait for a person to notice.

Three properties are pinned here:

* the trigger is records only: the host's typing of the row that opened the
  turn and the notice header the host formats. A person's message carrying the
  same text, a zero exit and a killed watcher get nothing;
* re-arming in the turn is read from the turn's own tool results (a notifying
  background spawn, a background `delegate_task`, a scheduled follow-up job),
  never from what the reply says;
* the session-wide "this session arms watchers" latch does not silence the
  sentence, because the session that armed the watcher which just failed has
  by definition armed one before.

The notice texts below are copied from the host's formatters
(`tools/process_registry_notifications.py::format_process_notification`,
`gateway/run_notifications.py::_format_coalesced_process_completions`) and the
`internal_notification` row kind the gateway gives them on Discord.
"""

from __future__ import annotations

import json
import unittest
from pathlib import Path
from tempfile import TemporaryDirectory

from _local_package import load_local_package

load_local_package()

from omh.plugin_bundle.omh.hooks.llm_hooks import pre_llm_call  # noqa: E402
from omh.plugin_bundle.omh.hooks.nudge_budget import reset_nudge_budget  # noqa: E402
from omh.plugin_bundle.omh.hooks.result_transforms import (  # noqa: E402
    transform_llm_output,
    transform_tool_result,
)
from omh.plugin_bundle.omh.remote_wait_nudge import (  # noqa: E402
    FAILED_WAIT_STOP_TEXTS,
    FAILED_WAIT_TEXT,
    PROCESS_RECORD_FILENAME,
    failed_processes,
    failed_wait_context,
    remote_wait_declines,
    reply_language,
    reset_remote_wait_state,
)

FOOTER = (
    "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. "
    "Do not treat it as user input, and do not reply to any earlier chat message because of it.]"
)
FAILED_NOTICE = (
    "[khope] [IMPORTANT: Background process proc_9bf1 exited (exit code 1).\n"
    "Command: bash scripts/pr_merge_watcher.sh 2433 0188215d2 frirenai /tmp/w.log\n"
    "Output:\nCHECKS FAILED aggregate]\n\n" + FOOTER
)
KILLED_NOTICE = (
    "[khope] [IMPORTANT: Background process proc_old terminated by process.kill (exit code -15, SIGTERM).\n"
    "Command: bash scripts/pr_merge_watcher.sh 2433 old\nOutput:\n]\n\n" + FOOTER
)
PASSED_NOTICE = (
    "[IMPORTANT: Background process proc_ok completed normally (exit code 0).\n"
    "Command: gh pr checks 2433 --watch\nOutput:\nall checks passed]"
)
BATCH_NOTICE = (
    "[IMPORTANT: 2 background processes completed for this session.\n"
    "Treat these results as one completion batch and send at most one consolidated user-facing response.\n"
    "\n- proc_a: exit_code=0, reason=exited\nok\n"
    "\n- proc_b: exit_code=7, reason=exited\nCONFLICT\n"
    "If a result does not change the current conclusion, absorb it silently.]"
)
NOTICE_KIND = "internal_notification"


class FailedWaitTestCase(unittest.TestCase):
    def setUp(self) -> None:
        super().setUp()
        reset_nudge_budget()
        reset_remote_wait_state()
        self.addCleanup(reset_nudge_budget)
        self.addCleanup(reset_remote_wait_state)
        self._tmp = TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.home = Path(self._tmp.name) / "hermes"
        self.home.mkdir()

    def start(self, message: str = FAILED_NOTICE, kind: object = NOTICE_KIND, *, turn: str = "t1") -> str:
        return failed_wait_context(
            user_message=message,
            display_kind=kind,
            session_id="s1",
            turn_id=turn,
            hermes_home=str(self.home),
        )

    def end(self, reply: str = "CI failed on the aggregate check.", *, turn: str = "t1") -> str | None:
        return transform_llm_output(
            response_text=reply,
            session_id="s1",
            model="any-model",
            platform="discord",
            turn_id=turn,
            hermes_home=str(self.home),
        )

    def tool(self, name: str, args: dict[str, object], result: dict[str, object], *, turn: str = "t1") -> None:
        transform_tool_result(
            tool_name=name,
            args=args,
            result=json.dumps(result),
            session_id="s1",
            turn_id=turn,
            hermes_home=str(self.home),
        )


class NoticeParsingTests(unittest.TestCase):
    def test_a_failed_watcher_is_read_from_the_host_header(self) -> None:
        self.assertEqual(failed_processes(FAILED_NOTICE), [("proc_9bf1", 1)])

    def test_a_kill_is_not_a_failure(self) -> None:
        # A superseded watcher is killed on purpose; its -15 says nothing
        # about the work, and a re-pinned watcher is already running.
        self.assertEqual(failed_processes(KILLED_NOTICE), [])
        self.assertEqual(
            failed_processes(
                "[IMPORTANT: 2 background processes completed for this session.\n"
                "\n- proc_x: exit_code=-15, reason=killed\n]"
            ),
            [],
        )

    def test_a_zero_exit_is_not_a_failure(self) -> None:
        self.assertEqual(failed_processes(PASSED_NOTICE), [])

    def test_the_coalesced_batch_names_only_its_failed_lines(self) -> None:
        self.assertEqual(failed_processes(BATCH_NOTICE), [("proc_b", 7)])

    def test_a_header_quoted_inside_a_line_is_not_a_notice(self) -> None:
        # Only a block that opens with the header is read; a sentence that
        # mentions one mid-line is prose.
        quoted = "the log said [IMPORTANT: Background process p exited (exit code 1). and moved on"
        self.assertEqual(failed_processes(quoted), [])

    def test_anything_else_reads_as_no_failure(self) -> None:
        for value in (None, 3, "", "CI failed, exit code 1", "[IMPORTANT: something else]"):
            with self.subTest(value=value):
                self.assertEqual(failed_processes(value), [])


class TurnStartTests(FailedWaitTestCase):
    def test_a_failed_watcher_turn_gets_the_directive(self) -> None:
        text = self.start()
        self.assertEqual(text, FAILED_WAIT_TEXT.format(process="proc_9bf1", code=1))
        self.assertIn("[OMH failed wait]", text)
        self.assertIn("notify=true", text)

    def test_a_person_typing_the_same_text_gets_nothing(self) -> None:
        # The row kind is the host's record of who wrote it; text alone never
        # opens the directive, in any wording.
        for kind in ("", None, "steer", 5):
            with self.subTest(kind=kind):
                self.assertEqual(self.start(kind=kind), "")

    def test_a_kill_or_a_pass_gets_nothing(self) -> None:
        self.assertEqual(self.start(KILLED_NOTICE), "")
        self.assertEqual(self.start(PASSED_NOTICE, "process_complete"), "")

    def test_another_live_notifying_watcher_suppresses_it(self) -> None:
        # Something else is still armed and will wake the session.
        (self.home / PROCESS_RECORD_FILENAME).write_text(
            json.dumps(
                [{"session_id": "proc_live", "parent_session_id": "s1", "notify_on_complete": True}]
            ),
            encoding="utf-8",
        )
        self.assertEqual(self.start(), "")
        self.assertEqual(remote_wait_declines().get("failed_wait_other_waiter_live"), 1)

    def test_an_unreadable_record_declines(self) -> None:
        (self.home / PROCESS_RECORD_FILENAME).write_text("{not json", encoding="utf-8")
        self.assertEqual(self.start(), "")
        self.assertEqual(remote_wait_declines().get("process_record_unreadable"), 1)

    def test_a_delegated_child_gets_nothing(self) -> None:
        text = failed_wait_context(
            user_message=FAILED_NOTICE,
            display_kind=NOTICE_KIND,
            session_id="child",
            turn_id="t1",
            hermes_home=str(self.home),
            delegated=True,
        )
        self.assertEqual(text, "")

    def test_it_reaches_the_turn_through_pre_llm_call(self) -> None:
        omh = Path(self._tmp.name) / "omh"
        payload = pre_llm_call(
            omh_home=str(omh),
            hermes_home=str(self.home),
            session_id="s1",
            turn_id="t1",
            user_message=FAILED_NOTICE,
            conversation_history=[{"role": "user", "content": FAILED_NOTICE, "display_kind": NOTICE_KIND}],
            is_first_turn=False,
            platform="discord",
        )
        self.assertIn("[OMH failed wait]", str((payload or {}).get("context", "")))

    def test_a_person_turn_through_pre_llm_call_carries_no_directive(self) -> None:
        omh = Path(self._tmp.name) / "omh"
        payload = pre_llm_call(
            omh_home=str(omh),
            hermes_home=str(self.home),
            session_id="s1",
            turn_id="t1",
            user_message=FAILED_NOTICE,
            conversation_history=[{"role": "user", "content": FAILED_NOTICE}],
            is_first_turn=False,
            platform="discord",
        )
        self.assertNotIn("[OMH failed wait]", str((payload or {}).get("context", "")))


class TurnEndTests(FailedWaitTestCase):
    def test_a_turn_that_rearms_nothing_ends_on_the_sentence(self) -> None:
        self.start()
        reply = "CI failed on the aggregate check: a trailing space in site/index.html."
        self.assertEqual(self.end(reply), f"{reply}\n\n{FAILED_WAIT_STOP_TEXTS['en']}")

    def test_the_sentence_follows_the_reply_language(self) -> None:
        replies = {
            "en": "CI failed again on the aggregate check.",
            "ko": "CI가 다시 실패했어. 원인은 줄 끝 공백이야.",
            "ja": "CIがまた失敗しました。原因は行末の空白です。",
            "zh": "持续集成再次失败，原因是行尾空格。",
            "zh-Hant": "持續整合再次失敗，原因是行尾空白。",
        }
        for index, (language, reply) in enumerate(replies.items()):
            with self.subTest(language=language):
                turn = f"t{index}"
                self.start(turn=turn)
                self.assertEqual(self.end(reply, turn=turn), f"{reply}\n\n{FAILED_WAIT_STOP_TEXTS[language]}")

    def test_a_notifying_background_spawn_this_turn_silences_it(self) -> None:
        self.start()
        self.tool(
            "terminal",
            {"command": "bash scripts/pr_merge_watcher.sh 2433 9d7ae8c frirenai /tmp/w.log", "background": True},
            {"output": "Background process started", "session_id": "proc_new", "exit_code": 0, "notify_on_complete": True},
        )
        self.assertIsNone(self.end())
        self.assertEqual(remote_wait_declines().get("failed_wait_rearmed"), 1)

    def test_a_silent_background_spawn_does_not_count(self) -> None:
        self.start()
        self.tool(
            "terminal",
            {"command": "sleep 600", "background": True},
            {"output": "Background process started", "session_id": "proc_quiet", "exit_code": 0, "notify_on_complete": False},
        )
        self.assertIsNotNone(self.end())

    def test_a_background_delegation_this_turn_silences_it(self) -> None:
        self.start()
        self.tool(
            "delegate_task",
            {"goal": "fix the failing check"},
            {"status": "dispatched", "mode": "background", "count": 1, "delegation_id": "deleg_1"},
        )
        self.assertIsNone(self.end())

    def test_a_scheduled_follow_up_job_this_turn_silences_it(self) -> None:
        self.start()
        self.tool(
            "cronjob_manage",
            {"action": "create", "schedule": "once in 45m", "prompt": "merge PR 2433 if green"},
            {"success": True, "job_id": "abc", "name": "PR 2433 merge follow-up"},
        )
        self.assertIsNone(self.end())

    def test_listing_or_removing_jobs_arms_nothing(self) -> None:
        for action in ("list", "remove", "pause"):
            with self.subTest(action=action):
                turn = f"t-{action}"
                self.start(turn=turn)
                self.tool("cronjob_manage", {"action": action}, {"success": True, "jobs": []}, turn=turn)
                self.assertIsNotNone(self.end(turn=turn))

    def test_a_failed_dispatch_arms_nothing(self) -> None:
        self.start()
        self.tool("delegate_task", {"goal": "x"}, {"status": "rejected", "error": "no slot"})
        self.tool("cronjob_manage", {"action": "create"}, {"success": False, "error": "bad schedule"})
        self.assertIsNotNone(self.end())

    def test_the_session_wide_latch_does_not_silence_it(self) -> None:
        # The session armed the watcher that just failed in an earlier turn,
        # so it carries the session latch; that must not read as re-armed.
        self.tool(
            "terminal",
            {"command": "gh pr checks 2433 --watch", "background": True},
            {"output": "Background process started", "session_id": "proc_9bf1", "exit_code": 0, "notify_on_complete": True},
            turn="t0",
        )
        self.start()
        self.assertIsNotNone(self.end())

    def test_rearming_in_an_earlier_turn_does_not_count(self) -> None:
        # A delegation dispatched before the failure belongs to that turn; the
        # turn the failed notice opened has to arm its own next wake.
        self.tool(
            "delegate_task",
            {"goal": "x"},
            {"status": "dispatched", "mode": "background", "count": 1},
            turn="t0",
        )
        self.start()
        self.assertIsNotNone(self.end())

    def test_a_watcher_still_live_at_the_end_silences_it(self) -> None:
        self.start()
        (self.home / PROCESS_RECORD_FILENAME).write_text(
            json.dumps([{"session_id": "proc_x", "parent_session_id": "s1", "notify_on_complete": True}]),
            encoding="utf-8",
        )
        self.assertIsNone(self.end())

    def test_wording_alone_cannot_silence_it(self) -> None:
        # Every true sentence a session writes about re-arming, with nothing
        # armed in the records.
        self.start()
        reply = (
            "Fixed and pushed; I re-armed the merge watcher in the background and "
            "a notice will arrive when CI finishes."
        )
        self.assertEqual(self.end(reply), f"{reply}\n\n{FAILED_WAIT_STOP_TEXTS['en']}")

    def test_a_turn_no_failed_notice_opened_is_untouched(self) -> None:
        self.start(PASSED_NOTICE, "process_complete")
        self.assertIsNone(self.end())

    def test_the_latch_belongs_to_its_turn(self) -> None:
        self.start(turn="t1")
        self.assertIsNone(self.end(turn="t2"))


class TextTests(unittest.TestCase):
    def test_the_texts_are_short_and_pinned(self) -> None:
        self.assertEqual(len(FAILED_WAIT_TEXT.format(process="proc_9bf1", code=1)), 415)
        self.assertEqual(
            {language: len(text) for language, text in FAILED_WAIT_STOP_TEXTS.items()},
            {"en": 80, "ko": 48, "ja": 46, "zh": 26, "zh-Hant": 29},
        )

    def test_each_stop_sentence_is_in_its_own_language(self) -> None:
        self.assertEqual(sorted(FAILED_WAIT_STOP_TEXTS), ["en", "ja", "ko", "zh", "zh-Hant"])
        for language, text in FAILED_WAIT_STOP_TEXTS.items():
            with self.subTest(language=language):
                self.assertEqual(reply_language(text), language)
                self.assertNotIn("[OMH", text)
                for name in ("Codex", "Claude", "Hermes", "gh ", "git ", "CI"):
                    self.assertNotIn(name, text)

    def test_each_stop_sentence_passes_the_reply_lint(self) -> None:
        from omh.quality.reply_lint import build_reply_lint, record_term_vocabulary

        for language, text in FAILED_WAIT_STOP_TEXTS.items():
            with self.subTest(language=language):
                self.assertTrue(build_reply_lint(text)["ok"], build_reply_lint(text)["findings"])
                for term in record_term_vocabulary():
                    if term.isascii():
                        self.assertNotIn(term.lower(), text.lower())


if __name__ == "__main__":
    unittest.main()
