def value_mechanisms_for_skill(canonical_name: str, *, allow_retired: bool = True) -> tuple[str, ...]:
    """Return the reviewed value mechanisms for one catalog skill.

    Fails closed (`KeyError`) for any installable skill without a reviewed entry.
    Retired/non-installable catalog entries return `()` when `allow_retired=True`.
    """
    mechanisms = _SKILL_VALUE_MECHANISMS.get(canonical_name)
    if mechanisms is None:
        if allow_retired:
            from .catalog import installable_skill_names

            if canonical_name not in installable_skill_names():
                return ()
        raise KeyError(
            f"skill {canonical_name!r} has no reviewed entry in _SKILL_VALUE_MECHANISMS "
            "(src/skills/value_mechanisms.py)"
        )
    invalid = sorted(set(mechanisms) - _VALID_VALUE_MECHANISMS)
    if not mechanisms or invalid:
        raise ValueError(f"skill {canonical_name!r} has invalid value mechanisms: {invalid or 'empty'}")
    return mechanisms


def prose_template_review_skills() -> tuple[str, ...]:
    """Canonical names of installable skills flagged for base-model lift review."""
    from .catalog import installable_skill_names

    installable = set(installable_skill_names())
    return tuple(
        sorted(
            name
            for name, mechanisms in _SKILL_VALUE_MECHANISMS.items()
            if name in installable and VALUE_MECHANISM_PROSE_TEMPLATE_REVIEW in mechanisms
        )
    )
