def _feature_surface_harness(
    name: str,
    purpose: str,
    use_when: str,
    required_inputs: tuple[str, ...],
    expected_outputs: tuple[str, ...],
    *,
    quality_tier: str,
    evidence_ladder: tuple[str, ...],
    wrapper_actions: tuple[str, ...],
    overclaim_guard: str,
) -> HarnessDefinition:
    return HarnessDefinition(
        name,
        purpose,
        use_when,
        required_inputs,
        expected_outputs,
        ("card is prepared or a missing decision is surfaced", "observed evidence is separated from prepared guidance"),
        ("validate required fields", "check not-evidence boundaries", "record only observed external actions"),
        "If a required target, credential, runtime, or observation is missing, show a blocker or confirmation action instead of claiming completion.",
        (f"{name}_scoped", f"{name}_card_prepared", f"{name}_status_recorded"),
        "Record this harness as Hermes-retained orchestration; external runtime/platform/file/memory/connector evidence requires a separate observed artifact.",
        "metadata_only",
        quality_tier=quality_tier,
        quality_bar=(
            "Name the workflow objective, owner, input boundary, next action, and stop condition.",
            "Represent prepared, observed, blocked, and missing evidence as separate states.",
            "Never upgrade a card, blueprint, or readiness check into external execution proof.",
        ),
        evidence_ladder=evidence_ladder,
        wrapper_actions=wrapper_actions,
        overclaim_guards=(overclaim_guard,),
    )


