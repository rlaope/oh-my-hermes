"""Build a TUI-only Hermes home outside `profiles/` for the own-runtime spike.

Run on Hermes' interpreter (it needs Hermes' PyYAML), never through the `hermes` launcher:

    HERMES_AGENT=~/.hermes/hermes-agent \
    ~/.hermes/tools/python-3.14.9*/bin/python3 -I tools/qa/tui_own_runtime/build_sandbox.py <sandbox-root> [--idle-exit 30]

Writes under <sandbox-root>:
    hermes/      the TUI home: config.yaml (root's sections, platforms disabled, idle exit shortened),
                 .env (root's, messaging tokens removed), auth.json (copy), SOUL.md (symlink),
                 skills/ (per-skill symlinks: root ∪ served profiles, root wins), plugins/omh (symlink)
    omh/         an empty OMH home the plugin writes into (never the live ~/.omh)
    cwd/         a fresh git repository for the session's directory
Prints a JSON summary (skill union, clashes, scrubbed names) on stdout.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

HERMES_AGENT = Path(os.environ.get("HERMES_AGENT", "~/.hermes/hermes-agent")).expanduser()
sys.path.insert(0, str(HERMES_AGENT))
import hermes_bootstrap  # noqa: E402,F401  (selects Hermes' dependency environment: PyYAML lives there)
import yaml  # noqa: E402

ROOT_HOME = Path(os.environ.get("ROOT_HERMES_HOME", "~/.hermes")).expanduser()
# Sections carried from the root config. Everything not listed stays at Hermes' defaults in the TUI home.
CARRIED_SECTIONS = (
    "model", "providers", "agent", "terminal", "browser", "tool_loop_guardrails", "compression",
    "prompt_caching", "display", "memory", "delegation", "skills", "command_allowlist", "plugins",
    "streaming", "telemetry", "updates", "_config_version", "session_reset", "mcp_servers",
    "known_plugin_toolsets", "fallback_providers", "auxiliary", "web", "database", "runtime",
)
# Messaging credentials never reach the TUI home (one bot token polled by two gateways is Hermes' own warning).
TOKEN_NAME_PARTS = ("DISCORD_", "SLACK_", "TELEGRAM_", "MATRIX_", "MATTERMOST_", "WEIXIN_", "WECOM_", "QQ_",
                    "FEISHU_", "LARK_", "WHATSAPP_", "SIGNAL_", "TEAMS_", "GOOGLE_CHAT_", "YUANBAO_", "MSGRAPH_",
                    "HOMEASSISTANT_", "HA_TOKEN", "HA_URL")


def served_profiles(root: Path) -> list[str]:
    try:
        record = json.loads((root / "gateway_state.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        record = {}
    served = [name for name in record.get("served_profiles", []) if isinstance(name, str) and name != "default"]
    if not served and (root / "profiles").is_dir():
        served = sorted(p.name for p in (root / "profiles").iterdir() if (p / "skills").is_dir())
    return served


def build(sandbox: Path, idle_exit: int) -> dict:
    home, omh_home, cwd = sandbox / "hermes", sandbox / "omh", sandbox / "cwd"
    for path in (home, omh_home, cwd, home / "skills", home / "plugins", home / "logs"):
        path.mkdir(parents=True, exist_ok=True)
        os.chmod(path, 0o700)
    os.chmod(sandbox, 0o700)

    source = yaml.safe_load((ROOT_HOME / "config.yaml").read_text(encoding="utf-8")) or {}
    config = {key: source[key] for key in CARRIED_SECTIONS if key in source}
    # Overrides: no messaging adapter, a short idle exit, the plugin's OMH home in the sandbox, OMH's skills kept.
    config["gateway"] = {"unmanaged_idle_exit_seconds": idle_exit}
    config["platforms"] = {}
    plugins = config.setdefault("plugins", {})
    entries = plugins.setdefault("entries", {})
    omh_entry = entries.setdefault("omh", {})
    omh_entry.setdefault("settings", {})["omh_home"] = str(omh_home)
    plugins["enabled"] = ["omh"]  # the bot-side plugins (homeassistant, herdr) are not the TUI's
    plugins["disabled"] = []
    (home / "config.yaml").write_text(
        f"# Generated by the own-runtime spike from {ROOT_HOME / 'config.yaml'}\n"
        + yaml.safe_dump(config, sort_keys=False, allow_unicode=True), encoding="utf-8")
    os.chmod(home / "config.yaml", 0o600)

    scrubbed: list[str] = []
    kept: list[str] = []
    env_lines = []
    for line in (ROOT_HOME / ".env").read_text(encoding="utf-8").splitlines() if (ROOT_HOME / ".env").is_file() else []:
        name = line.split("=", 1)[0].strip()
        if line.strip() and not line.lstrip().startswith("#") and any(part in name for part in TOKEN_NAME_PARTS):
            scrubbed.append(name)
            continue
        if "=" in line and not line.lstrip().startswith("#"):
            kept.append(name)
        env_lines.append(line)
    (home / ".env").write_text("\n".join(env_lines) + "\n", encoding="utf-8")
    os.chmod(home / ".env", 0o600)

    if (ROOT_HOME / "auth.json").is_file():
        shutil.copyfile(ROOT_HOME / "auth.json", home / "auth.json")
        os.chmod(home / "auth.json", 0o600)
    for name in ("SOUL.md",):
        if (ROOT_HOME / name).exists():
            (home / name).symlink_to(ROOT_HOME / name)

    union: dict[str, str] = {}
    clashes: list[dict] = []
    roots = [("default", ROOT_HOME / "skills")] + [(p, ROOT_HOME / "profiles" / p / "skills") for p in served_profiles(ROOT_HOME)]
    for owner, skills in roots:
        if not skills.is_dir():
            continue
        for skill in sorted(skills.iterdir()):
            if not (skill / "SKILL.md").is_file() and not skill.is_dir():
                continue
            if skill.name in union:
                clashes.append({"skill": skill.name, "kept": union[skill.name], "dropped": owner})
                continue
            union[skill.name] = owner
            (home / "skills" / skill.name).symlink_to(skill)
    plugin = ROOT_HOME / "plugins" / "omh"
    if plugin.is_dir():
        (home / "plugins" / "omh").symlink_to(plugin)

    subprocess.run(["git", "init", "-q", str(cwd)], check=True, stdin=subprocess.DEVNULL)
    return {
        "sandbox": str(sandbox), "hermes_home": str(home), "omh_home": str(omh_home), "cwd": str(cwd),
        "served_profiles": [owner for owner, _ in roots[1:]],
        "skills": sorted(union), "skill_count": len(union), "clashes": clashes,
        "env_kept": kept, "env_scrubbed": scrubbed,
        "config_sections": sorted(config), "idle_exit_seconds": idle_exit,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("sandbox")
    parser.add_argument("--idle-exit", type=int, default=30)
    args = parser.parse_args()
    summary = build(Path(args.sandbox).resolve(), args.idle_exit)
    print(json.dumps(summary, indent=1, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
